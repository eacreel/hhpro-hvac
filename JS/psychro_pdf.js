    function textWidth(str, size, bold) {
        var tbl = bold ? HELV_BOLD : HELV, w = 0;
        for (var i = 0; i < str.length; i++) {
            var c = str.charCodeAt(i);
            w += (c >= 32 && c <= 126) ? tbl[c - 32] : 556;
        }
        return w * size / 1000;
    }

    // Map to WinAnsi-safe text: the few symbols the page uses that are
    // outside Latin-1 get ASCII stand-ins.
    function sanitize(str) {
        return String(str)
            .replace(/→/g, '->').replace(/←/g, '<-')
            .replace(/−/g, '-').replace(/–|—/g, '-')
            .replace(/’/g, "'").replace(/“|”/g, '"')
            .replace(/…/g, '...').replace(/✓|✔/g, 'OK').replace(/✗|✘/g, 'X')
            .replace(/∞/g, 'inf').replace(/Δ/g, 'd');
    }

    function pdfString(str) {
        var s = sanitize(str), out = '';
        for (var i = 0; i < s.length; i++) {
            var c = s.charCodeAt(i);
            if (c > 255) c = 63; // '?'
            if (c === 40 || c === 41 || c === 92) out += '\\' + String.fromCharCode(c);
            else if (c < 32 || c > 126) out += '\\' + ('00' + c.toString(8)).slice(-3);
            else out += String.fromCharCode(c);
        }
        return '(' + out + ')';
    }

    function num(n) {
        return (Math.round(n * 100) / 100).toString();
    }

    function hexToRgb(hex) {
        var h = hex.replace('#', '');
        if (h.length === 3) h = h[0] + h[0] + h[1] + h[1] + h[2] + h[2];
        var n = parseInt(h, 16);
        return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255];
    }

    function rgbOp(hex, stroke) {
        var c = hexToRgb(hex);
        return num(c[0]) + ' ' + num(c[1]) + ' ' + num(c[2]) + (stroke ? ' RG' : ' rg');
    }

