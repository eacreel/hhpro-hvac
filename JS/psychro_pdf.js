/* ============================================================
   HHpro - Psychrometric report PDF
   ------------------------------------------------------------
   Builds a one-or-more page Letter PDF for a psychrometric
   calculation: title, the chart (converted from the same SVG the
   page draws, as vector line work), then the input/result blocks.

     HHpro.PsychroPdf.build({
         title: 'Project Alpha - AHU-1 mixed air',
         subtitle: 'HHpro Psychrometrics · Sep 11, 2026 · 780 ft',
         blocks: [
             { title: 'Airflow', rows: [['Total airflow', '10,000 CFM'], ...] },
             { title: 'Air properties', table: { head: [...], rows: [[...], ...] } }
         ],
         svg: svgElement,
         footer: 'Generated by HHpro'
     }) -> Blob (application/pdf)

   Self-contained writer (no library): standard Helvetica fonts
   with WinAnsi encoding, one content stream per page, a simple
   xref table. The SVG conversion understands exactly what
   psychro_chart.js emits: rect, line, path (M/L), polygon,
   circle, text (with text-anchor and translate/rotate), groups
   with clip-path, and marker-end arrowheads. Colours come from a
   print palette keyed by the chart's CSS classes, so the PDF is
   dark-on-white regardless of the site theme.
   ============================================================ */

